from typing import Annotated, Literal
from typing_extensions import TypedDict
from langchain_core.messages import BaseMessage
from langchain_core.tools import tool
from langgraph.graph import StateGraph, START, END
from langgraph.graph.message import add_messages
from langgraph.prebuilt import ToolNode, tools_condition
from langchain_openai import ChatOpenAI
import requests

# ==========================================
# 1. DEFINE THE STATE (Memory)
# ==========================================
# This acts as the memory passing between nodes. 
# It keeps a running list of all messages (user, AI, and tool responses).
class AgentState(TypedDict):
    messages: Annotated[list[BaseMessage], add_messages]

# ==========================================
# 2. DEFINE THE TOOLS (Your .NET APIs)
# ==========================================
@tool
def fetch_pending_work_orders(status: str) -> str:
    """
    Fetches work orders from the database based on their status.
    Use this tool when the user asks about work orders or maintenance tasks.
    """
    # In reality, this will be: 
    # response = requests.get(f"https://your-dotnet-api/api/workorders?status={status}")
    # return response.json()
    
    # Mocking the JSON response from your ASP.NET backend for this example:
    return '[{"id": 4052, "task": "HVAC Repair", "status": "Pending Maker Approval"}]'

tools = [fetch_pending_work_orders]

# ==========================================
# 3. DEFINE THE NODES (The Workers)
# ==========================================

# Initialize the LLM and bind the tools to it
llm = ChatOpenAI(model="gpt-4o-mini", temperature=0)
llm_with_tools = llm.bind_tools(tools)

def agent_node(state: AgentState):
    """
    NODE 1: The Brain.
    Reads the conversation history and decides to either reply directly 
    or output a tool command.
    """
    response = llm_with_tools.invoke(state["messages"])
    # We return the response so LangGraph appends it to the state's message list
    return {"messages": [response]}

# NODE 2: The API Caller.
# LangGraph's prebuilt ToolNode automatically reads the LLM's command, 
# runs the matching Python function, and returns the JSON output.
tool_node = ToolNode(tools)

# ==========================================
# 4. BUILD THE GRAPH (The Routing)
# ==========================================
workflow = StateGraph(AgentState)

# Add our two nodes to the graph
workflow.add_node("agent", agent_node)
workflow.add_node("tools", tool_node)

# Set where the graph starts
workflow.add_edge(START, "agent")

# CONDITIONAL EDGE: The Router
# `tools_condition` is LangGraph's built-in router. 
# If the agent output a tool call -> route to "tools".
# If the agent output plain text -> route to END.
workflow.add_conditional_edges(
    "agent",
    tools_condition,
)

# Loop back to the agent after the tool finishes fetching data
workflow.add_edge("tools", "agent")

# Compile it into an executable app
app = workflow.compile()

# ==========================================
# 5. RUN THE AGENT
# ==========================================
if __name__ == "__main__":
    user_input = "Can you show me the pending work orders?"
    
    # We pass the user's message into the graph
    initial_state = {"messages": [("user", user_input)]}
    
    # Stream the output so we can see what nodes are executing
    for event in app.stream(initial_state):
        for node_name, state_update in event.items():
            print(f"--- Just completed node: {node_name} ---")
            
            # Print the latest message generated by this node
            latest_msg = state_update["messages"][-1]
            if hasattr(latest_msg, "content") and latest_msg.content:
                print(latest_msg.content)
            print("\n")